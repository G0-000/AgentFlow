from __future__ import annotations

from datetime import UTC, datetime


def now_utc_iso() -> str:
    """返回当前 UTC 时间的 ISO 字符串（全库唯一时间戳来源）。

    注意: 存 UTC，显示时由展示层转本地时区（M8 前端处理）。
    """
    return datetime.now(UTC).isoformat()
