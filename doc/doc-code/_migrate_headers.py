def replace_header(path: Path, new_header: str) -> bool:
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)
    idx = None
    for i, ln in enumerate(lines):
        if ln.startswith(("from ", "import ")):
            idx = i
            break
    if idx is None:
        # 无 import 的文件（纯包入口）：整体替换
        path.write_text(new_header.rstrip() + "\n", encoding="utf-8")
        return True
    body = "".join(lines[idx:])
    path.write_text(new_header.rstrip() + "\n\n" + body, encoding="utf-8")
    return True


def main() -> None:
    done = []
    for rel, header in H.items():
        p = ROOT / rel
        if p.exists():
            replace_header(p, header)
            done.append(rel)
    for rel, (pkg, duty, source, milestone, note) in INIT_HEADERS.items():
        p = ROOT / rel
        if p.exists():
            replace_header(p, build_init_header(pkg, duty, source, milestone, note))
            done.append(rel)
    print(f"迁移完成: {len(done)} 个文件")
    for d in done:
        print(" ", d)


if __name__ == "__main__":
    main()
